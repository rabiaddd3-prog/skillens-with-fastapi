"""One-page PDF summary of a job match and its roadmap (rendered with PyMuPDF's HTML Story).

Contains only what the user already sees on screen: job, scores, skill evidence and roadmap steps.
The CV text itself is never included. Labels follow the page language (en / tr).
"""
from __future__ import annotations

import html
from datetime import date

from .i18n import norm_lang

