"""One-page PDF summary of a job match and its roadmap (rendered with PyMuPDF's HTML Story).

Contains only what the user already sees on screen: job, scores, skill evidence and roadmap steps.
The CV text itself is never included.
"""
from __future__ import annotations

import html
from datetime import date

STATUS_TEXT = {
    "cv_and_quiz": "CV and quiz", "cv_only": "CV only", "quiz_only": "quiz only",
    "weak_quiz": "weak quiz result", "missing": "missing",
}

CSS = """
* { font-family: sans-serif; }
body { font-size: 10pt; color: #14213d; }
h1 { font-size: 18pt; margin: 0 0 2pt 0; }
h2 { font-size: 12pt; margin: 12pt 0 4pt 0; border-bottom: 1px solid #d9dee7; }
.sub { color: #5a6478; font-size: 9pt; }
table { border-collapse: collapse; width: 100%; }
td, th { border-bottom: 1px solid #d9dee7; padding: 3pt 4pt; text-align: left; vertical-align: top; }
th { color: #5a6478; font-size: 8pt; }
.score { font-size: 16pt; font-weight: bold; }
.sc { padding-right: 34pt; }
.step { margin: 0 0 8pt 0; }
.kind { color: #2f5d9e; font-size: 8pt; }
a { color: #2f5d9e; }
.note { color: #5a6478; font-size: 8pt; }
"""


def _pct(x):
    return "n/a" if x is None else f"{round(x * 100)}%"


def _quiz_cell(r: dict) -> str:
    q = r["quiz"]
    if not q:
        return "not evaluated" if r["quiz_state"] == "not_evaluated" else "no quiz"
    level = f", {q['level']}" if q.get("level") else ""
    return f"{_pct(q['ratio'])} ({q['correct']}/{q['total']}{level})"


def summary_html(job: dict, match: dict, roadmap: dict) -> str:
    e = html.escape
    s = match["scores"]
    rows = "".join(
        f"<tr><td>{e(r['skill'])}</td><td>{e(STATUS_TEXT[r['status']])}</td>"
        f"<td>{'yes' if r['in_cv'] else 'no'}</td>"
        f"<td>{_quiz_cell(r)}</td></tr>"
        for r in match["skills"])
    if roadmap["steps"]:
        steps = "".join(
            f"<div class='step'><b>{st['order']}. {e(st['title'])}</b> "
            f"<span class='kind'>{'prerequisite' if st['kind'] == 'prerequisite' else 'gap'}</span><br/>"
            f"{e(st['reason'])}<br/><i>Goal:</i> {e(st['goal'])}"
            + "".join(f"<br/>&#8226; <a href='{e(c['url'])}'>{e(c['title'])}</a> ({e(c['provider'])})" for c in st["courses"])
            + "</div>"
            for st in roadmap["steps"])
    else:
        steps = f"<p>{e(roadmap.get('message') or 'No gaps found.')}</p>"
    notes = "".join(f"<li>{e(n)}</li>" for n in match.get("notes", []))
    w = match.get("weights", {"cv": 0.5, "quiz": 0.5})
    return f"""
<img src="logo.png" width="150"/>
<h1>Summary</h1>
<p class="sub">{e(job['title'])}{' &#183; ' + e(job['company']) if job.get('company') else ''} &#183; {date.today().isoformat()}</p>
<h2>Scores</h2>
<table class="scores"><tr>
  <td class="sc"><span class="score">{_pct(s['combined'])}</span><br/>combined</td>
  <td class="sc"><span class="score">{_pct(s['cv_coverage'])}</span><br/>CV coverage</td>
  <td class="sc"><span class="score">{_pct(s['quiz_performance'])}</span><br/>quiz performance</td>
  <td class="sc"><span class="score">{_pct(s['quiz_coverage'])}</span><br/>quiz coverage</td>
</tr></table>
<p class="note">combined = {w['cv']} x CV coverage + {w['quiz']} x quiz performance; without quiz evidence for the job's
topics, combined = CV coverage.</p>
{f'<ul class="note">{notes}</ul>' if notes else ''}
<h2>Skills required by the job</h2>
<table><tr><th>Skill</th><th>Evidence</th><th>In CV</th><th>Quiz</th></tr>{rows}</table>
<h2>Learning roadmap</h2>
{steps}
<p class="note">Generated by SkillLens (NLP course prototype). Skills were extracted from the job ad by a fine-tuned
DistilBERT model and may contain errors. The CV text is not stored or included.</p>
"""


def summary_pdf(job: dict, match: dict, roadmap: dict) -> bytes:
    import io

    import pymupdf

    from pathlib import Path

    img_dir = Path(__file__).resolve().parents[1] / "web" / "img"  # logo.png (scripts/make_logo.py)
    story = pymupdf.Story(html=summary_html(job, match, roadmap), user_css=CSS, archive=pymupdf.Archive(str(img_dir)))
    buf = io.BytesIO()
    writer = pymupdf.DocumentWriter(buf)
    page = pymupdf.paper_rect("a4")
    where = page + (42, 42, -42, -42)
    more = True
    while more:
        dev = writer.begin_page(page)
        more, _ = story.place(where)
        story.draw(dev)
        writer.end_page()
    writer.close()
    return buf.getvalue()
