CSS = """
* { font-family: sans-serif; }
body { font-size: 10pt; color: #14213d; }
h1 { font-size: 18pt; margin: 0 0 2pt 0; }
h2 { font-size: 12pt; margin: 12pt 0 4pt 0; border-bottom: 1px solid #d9dee7; }
.sub { color: #5a6478; font-size: 9pt; }
table { border-collapse: collapse; width: 100%; }
td, th { border-bottom: 1px solid #d9dee7; padding: 3pt 4pt; text-align: left; vertical-align: top; }
th { color: #5a6478; font-size: 8pt; }
.score { font-size: 16pt; font-weight: bold; }
.sc { padding-right: 34pt; }
.step { margin: 0 0 8pt 0; }
.kind { color: #2f5d9e; font-size: 8pt; }
a { color: #2f5d9e; }
.note { color: #5a6478; font-size: 8pt; }
"""


def _pct(x, t):
    return t["na"] if x is None else f"{round(x * 100)}%"


def _quiz_cell(r: dict, t: dict) -> str:
    q = r["quiz"]
    if not q:
        return t["not_eval"] if r["quiz_state"] == "not_evaluated" else t["no_quiz"]
    level = f", {q['level']}" if q.get("level") else ""
    return f"{_pct(q['ratio'], t)} ({q['correct']}/{q['total']}{level})"


def summary_html(job: dict, match: dict, roadmap: dict, lang: str = "en") -> str:
    t = L[norm_lang(lang)]
    e = html.escape
    s = match["scores"]
    rows = "".join(
        f"<tr><td>{e(r['skill'])}</td><td>{e(t['status'][r['status']])}</td>"
        f"<td>{t['yes'] if r['in_cv'] else t['no']}</td>"
        f"<td>{e(_quiz_cell(r, t))}</td></tr>"
        for r in match["skills"])
    if roadmap["steps"]:
        steps = "".join(
            f"<div class='step'><b>{st['order']}. {e(st['title'])}</b> "
            f"<span class='kind'>{t['prereq'] if st['kind'] == 'prerequisite' else t['gap']}</span><br/>"
            f"{e(st['reason'])}<br/><i>{t['goal']}</i> {e(st['goal'])}"
            + "".join(f"<br/>&#8226; <a href='{e(c['url'])}'>{e(c['title'])}</a> ({e(c['provider'])})" for c in st["courses"])
            + "</div>"
            for st in roadmap["steps"])
    else:
        steps = f"<p>{e(roadmap.get('message') or t['no_gaps'])}</p>"
    notes = "".join(f"<li>{e(n)}</li>" for n in match.get("notes", []))
    w = match.get("weights", {"cv": 0.5, "quiz": 0.5})
    return f"""
<img src="logo.png" width="150"/>
<h1>{t['summary']}</h1>
<p class="sub">{e(job['title'])}{' &#183; ' + e(job['company']) if job.get('company') else ''} &#183; {date.today().isoformat()}</p>
<h2>{t['scores']}</h2>
<table class="scores"><tr>
  <td class="sc"><span class="score">{_pct(s['combined'], t)}</span><br/>{t['combined']}</td>
  <td class="sc"><span class="score">{_pct(s['cv_coverage'], t)}</span><br/>{t['cv_cov']}</td>
  <td class="sc"><span class="score">{_pct(s['quiz_performance'], t)}</span><br/>{t['quiz_perf']}</td>
  <td class="sc"><span class="score">{_pct(s['quiz_coverage'], t)}</span><br/>{t['quiz_cov']}</td>
</tr></table>
<p class="note">{e(t['formula'].format(cv=w['cv'], quiz=w['quiz']))}</p>
{f'<ul class="note">{notes}</ul>' if notes else ''}
<h2>{t['skills']}</h2>
<table><tr><th>{t['skill']}</th><th>{t['evidence']}</th><th>{t['in_cv']}</th><th>{t['quiz']}</th></tr>{rows}</table>
<h2>{t['roadmap']}</h2>
{steps}
<p class="note">{e(t['footer'])}</p>
"""


def summary_pdf(job: dict, match: dict, roadmap: dict, lang: str = "en") -> bytes:
    import io
    from pathlib import Path

    import pymupdf

    img_dir = Path(__file__).resolve().parents[1] / "web" / "img"  # logo.png (scripts/make_logo.py)
    story = pymupdf.Story(html=summary_html(job, match, roadmap, lang), user_css=CSS,
                          archive=pymupdf.Archive(str(img_dir)))
    buf = io.BytesIO()
    writer = pymupdf.DocumentWriter(buf)
    page = pymupdf.paper_rect("a4")
    where = page + (42, 42, -42, -42)
    more = True
    while more:
        dev = writer.begin_page(page)
        more, _ = story.place(where)
        story.draw(dev)
        writer.end_page()
    writer.close()
    return buf.getvalue()
