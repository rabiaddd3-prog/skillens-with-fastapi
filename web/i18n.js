let LANG = I18N[localStorage.getItem("skilllens-lang")] ? localStorage.getItem("skilllens-lang") : "en";

function t(key, vars = {}) {
  const s = I18N[LANG][key] ?? I18N.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
}

// data-i18n: text, data-i18n-html: trusted markup from the dictionary above, data-i18n-ph: placeholder,
// data-i18n-aria: aria-label, data-i18n-title: title. data-i18n-vars holds JSON values for {placeholders}.
function applyI18n(root = document) {
  const vars = (el) => (el.dataset.i18nVars ? JSON.parse(el.dataset.i18nVars) : {});
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n, vars(el)); });
  root.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml, vars(el)); });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  document.documentElement.lang = LANG;
  document.title = t("page.title");
}

function setLang(lang) {
  LANG = I18N[lang] ? lang : "en";
  localStorage.setItem("skilllens-lang", LANG);
  applyI18n();
  document.dispatchEvent(new CustomEvent("langchange", { detail: LANG }));
}
